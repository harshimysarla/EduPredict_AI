import { useQuery } from "@tanstack/react-query"
import { useNavigate } from "react-router-dom"
import { BrainCircuit, Sparkles } from "lucide-react"
import { api } from "@/lib/api"
import type { StudentSummary } from "@/types"
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card"
import { Button } from "@/components/ui/button"
import { Skeleton } from "@/components/ui/skeleton"
import { RiskBadge } from "@/components/shared/RiskBadge"
import { EmptyState } from "@/components/ui/empty-state"
import { formatDate, formatPercent } from "@/lib/utils"

export default function Predictions() {
  const navigate = useNavigate()

  const { data, isLoading } = useQuery({
    queryKey: ["predictions-page"],
    queryFn: () => api.get<StudentSummary[]>("/students?page_size=50&sort=risk_probability&order=desc"),
  })

  return (
    <div className="space-y-5">
      <div>
        <h1 className="text-2xl font-bold tracking-tight">Predictions</h1>
        <p className="mt-1 text-sm text-[var(--muted-foreground)]">
          AI risk predictions across your cohort. Run a fresh prediction from any student profile.
        </p>
      </div>

      <Card>
        <CardHeader>
          <CardTitle className="flex items-center gap-2">
            <Sparkles className="h-4 w-4 text-[var(--primary)]" /> Model status
          </CardTitle>
          <CardDescription>
            Predictions are generated by the active trained model (Random Forest or Logistic Regression). Open the Model
            Lab to compare and switch.
          </CardDescription>
        </CardHeader>
      </Card>

      <Card>
        <CardContent className="p-0">
          <div className="overflow-x-auto">
            <table className="w-full text-sm">
              <thead>
                <tr className="border-b border-[var(--border)] text-left text-xs uppercase tracking-wide text-[var(--muted-foreground)]">
                  <th className="px-5 py-3 font-medium">Student</th>
                  <th className="px-4 py-3 font-medium">Risk Probability</th>
                  <th className="px-4 py-3 font-medium">Risk Level</th>
                  <th className="px-4 py-3 font-medium">Last Prediction</th>
                  <th className="px-5 py-3 font-medium text-right">Action</th>
                </tr>
              </thead>
              <tbody>
                {isLoading &&
                  Array.from({ length: 6 }).map((_, i) => (
                    <tr key={i} className="border-b border-[var(--border)] last:border-0">
                      <td colSpan={5} className="px-5 py-2.5">
                        <Skeleton className="h-8 w-full" />
                      </td>
                    </tr>
                  ))}
                {data?.map((s) => (
                  <tr
                    key={s.id}
                    className="cursor-pointer border-b border-[var(--border)] transition-colors last:border-0 hover:bg-[var(--muted)]"
                    onClick={() => navigate(`/students/${s.id}?tab=predictions`)}
                  >
                    <td className="px-5 py-3">
                      <div>
                        <p className="font-medium">{s.full_name}</p>
                        <p className="text-xs text-[var(--muted-foreground)]">{s.student_id}</p>
                      </div>
                    </td>
                    <td className="px-4 py-3 font-semibold">{formatPercent(s.risk_probability, 1)}</td>
                    <td className="px-4 py-3">
                      <RiskBadge level={s.risk_level} />
                    </td>
                    <td className="px-4 py-3 text-xs text-[var(--muted-foreground)]">
                      {formatDate(s.last_prediction)}
                    </td>
                    <td className="px-5 py-3 text-right">
                      <Button
                        variant="outline"
                        size="sm"
                        onClick={(e) => {
                          e.stopPropagation()
                          navigate(`/students/${s.id}?tab=predictions`)
                        }}
                      >
                        <BrainCircuit className="h-4 w-4" /> View
                      </Button>
                    </td>
                  </tr>
                ))}
                {!isLoading && (!data || data.length === 0) && (
                  <tr>
                    <td colSpan={5} className="px-5 py-6">
                      <EmptyState
                        icon={BrainCircuit}
                        title="No predictions available"
                        description="Run predictions from student profiles once a model is trained."
                      />
                    </td>
                  </tr>
                )}
              </tbody>
            </table>
          </div>
        </CardContent>
      </Card>
    </div>
  )
}
